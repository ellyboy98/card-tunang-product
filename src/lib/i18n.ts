const STRINGS: Record<Lang, Record<StringKey, string>> = { ms, en };

export type Vars = Record<string, string | number>;

/** The string for `key` in `lang`, with `{name}` placeholders filled from `vars`. */
export function t(lang: Lang, key: StringKey, vars?: Vars): string {
  const s = STRINGS[lang][key];
  return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
}

export function isStringKey(v: string): v is StringKey {
  return v in ms;
}

/** "orang" in Malay; "guest" / "guests" in English. For the {people} placeholder. */
export function people(lang: Lang, n: number): string {
  return lang === "ms" ? "orang" : n === 1 ? "guest" : "guests";
}

/** Family-typed text: the English version when asked for and filled in, else the Malay. */
export function pick(lang: Lang, msText: string, enText: string | null | undefined): string {
  return lang === "en" && enText && enText.trim() ? enText : msText;
}

/** Preset labels carry both languages. */
export function label(lang: Lang, p: { label: string; labelEn: string }): string {
  return lang === "en" ? p.labelEn : p.label;
}
